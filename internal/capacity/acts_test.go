package capacity

import (
	"strings"
	"testing"
)

func TestWhatACallDoesInATree(t *testing.T) {
	const home, tree, above = "/h", "/h/p/shop", "/h/p"
	for _, c := range []struct {
		tool, input, cwd string
		acts             bool
	}{
		// reads, whatever they name
		{"Bash", `{"command":"gh pr checks 9 --repo owner/shop"}`, above, false},
		{"Bash", `{"command":"waitfor --timeout 9m --until 'gh pr checks 9 --repo owner/shop'"}`, above, false},
		{"Bash", `{"command":"cat /h/p/shop/a.go | grep -n x; rg y ~/p/shop"}`, above, false},
		{"Bash", `{"command":"git -C /h/p/shop log --oneline -3 && git -C shop status && git -C shop diff HEAD~1"}`, above, false},
		{"Bash", `{"command":"cd shop && git show HEAD && git stash list"}`, above, false},
		{"Bash", `{"command":"journalctl --user -u shop.service --since today"}`, above, false},
		{"Bash", `{"command":"git clone -q https://example.com/owner/shop"}`, "/h/.cache/x", false},
		{"Bash", `{"command":"sed -n 1,20p shop/a.go; find shop -name '*.go'"}`, above, false},
		{"Read", `{"file_path":"/h/p/shop/a.go"}`, above, false},
		{"Grep", `{"pattern":"x","path":"/h/p/shop"}`, above, false},
		{"Agent", `{"prompt":"never cd into /h/p/shop"}`, above, false},
		{"Write", `{"file_path":"/h/.cache/brief.md","content":"work in /h/p/shop"}`, above, false},
		{"mcp__x__y", `{"repo":"owner/shop"}`, above, false},
		// acts
		{"Bash", `{"command":"ls"}`, "/h/p/shop/sub", true},
		{"Bash", `{"command":"git -C /h/p/shop commit -qm x"}`, above, true},
		{"Bash", `{"command":"git -C ~/p/shop checkout -b topic"}`, above, true},
		{"Bash", `{"command":"cd shop && git reset --hard origin/main"}`, above, true},
		{"Bash", `{"command":"git -C shop stash"}`, above, true},
		{"Bash", `{"command":"git -C shop worktree add ../lane -b lane"}`, above, true},
		{"Bash", `{"command":"git -C other worktree add /h/p/shop/lane"}`, above, true},
		{"Bash", `{"command":"cd shop && go test ./..."}`, above, true},
		{"Bash", `{"command":"go build -C ./shop ./..."}`, above, true},
		{"Bash", `{"command":"echo x > shop/a.txt"}`, above, true},
		{"Bash", `{"command":"sed -i s/a/b/ shop/a.go"}`, above, true},
		{"Bash", `{"command":"rm -rf shop"}`, above, true},
		{"Bash", `{"command":"bash -lc 'cd /h/p/shop && make'"}`, above, true},
		{"Edit", `{"file_path":"/h/p/shop/a.go","old_string":"a","new_string":"b"}`, above, true},
		{"edit", `{"newString":"b","oldString":"a","filePath":"/h/p/shop/a.go"}`, above, true},
		{"exec", `tools.apply_patch("*** Begin Patch\n*** Update File: /h/p/shop/a.go\n@@")`, above, true},
		{"Bash", `{"command":"gh pr list --repo owner/shop --json number | xargs -n1 gh pr view"}`, above, false},
		{"Bash", `{"command":"cp -r /h/p/shop /h/.cache/x && rsync -a /h/p/shop/ /h/.cache/y/"}`, above, false},
		{"Bash", `{"command":"tar -C /h/p -czf /h/.cache/s.tgz shop"}`, above, false},
		{"Bash", `{"command":"git -C shop config --global user.name x"}`, above, false},
		{"exec_command", `{"cmd":"go test ./...","workdir":"/h/p/shop"}`, above, true},
		{"bash", `{"command":"make","workdir":"/h/p/shop"}`, above, true},
		{"mcp__t__run", `{"command":"make","cwd":"/h/p/shop"}`, above, true},
		{"Bash", `{"command":"make -C shop"}`, above, true},
		{"Bash", `{"command":"go -C shop test ./... && go test -C shop ./..."}`, above, true},
		{"Bash", `{"command":"npm --prefix shop test"}`, above, true},
		{"Bash", `{"command":"find shop -name '*.orig' -delete"}`, above, true},
		{"Bash", `{"command":"python3 -c 'open(\"/h/p/shop/a\",\"w\")'"}`, above, true},
		{"Bash", `{"command":"find /h/p/shop -name '*.orig' | xargs rm"}`, above, true},
		{"Bash", `{"command":"ls -d /h/p/shop | xargs -I{} git -C {} reset --hard"}`, above, true},
		{"shell", `{"command":["bash","-lc","cd shop && make"]}`, above, true},
		{"Bash", `{"command":"cd -- shop && make"}`, above, true},
		{"Bash", `{"command":"env -C /h/p/shop make"}`, above, true},
		{"Bash", `{"command":"timeout -s KILL 5m make -C shop"}`, above, true},
		{"Bash", `{"command":"cp /h/.cache/a.go /h/p/shop/a.go"}`, above, true},
		{"Bash", `{"command":"tar -xzf /h/.cache/s.tgz -C /h/p/shop"}`, above, true},
		{"Bash", `{"command":"cat <<'EOF' > /h/.cache/brief.md\nrun make in /h/p/shop\nEOF\nls"}`, above, false},
		{"Bash", `{"command":"journalctl -u shop --since today && systemctl --user status shop"}`, above, false},
		{"Bash", `{"command":"momentum case list --repo shop; tacit search shop"}`, above, false},
		{"Bash", `{"command":"git -C shop fetch origin && git -C shop branch --list"}`, above, false},
		{"Bash", `{"command":"echo done 2>&1 >/dev/null"}`, above, false},
		{"Bash", `{"command":"/h/p/shop/scripts/release.sh"}`, above, true},
		{"Bash", `{"command":"~/p/shop/bin/gen --all"}`, above, true},
		{"Bash", `{"command":"shop/scripts/gen.sh"}`, above, true},
		{"Bash", `{"command":"pytest shop && black shop"}`, above, true},
		{"Bash", `{"command":"npx prettier --write shop"}`, above, true},
		{"Bash", `{"command":"echo hi>/h/p/shop/a.txt"}`, above, true},
		{"Bash", `{"command":"CARGO_TARGET_DIR=/h/p/shop/target cargo build"}`, above, true},
		{"Bash", `{"command":"cd shop && gh pr merge 5 --delete-branch"}`, above, true},
		{"Bash", `{"command":"yq -i '.a = 1' shop/a.yaml"}`, above, true},
		{"Bash", `{"command":"git -C shop branch --set-upstream-to=origin/main"}`, above, true},
		{"Bash", `{"command":"git -C shop fetch origin main:main"}`, above, true},
		{"Bash", `{"command":"bash <<'EOF'\ncd /h/p/shop\nmake\nEOF"}`, above, true},
		{"Bash", `{"command":"python3 - <<'EOF'\nopen('/h/p/shop/a', 'w').write('x')\nEOF"}`, above, true},
		{"Bash", `{"command":"for f in shop/*.go; do wc -l $f; done"}`, above, false},
		{"Bash", `{"command":"for f in /h/p/shop/*.go; do grep -c x $f; done"}`, above, false},
		{"Bash", `{"command":"gh pr create --body-file - <<'EOF'\nchanged /h/p/shop/a.go\nEOF"}`, above, false},
		{"Bash", `{"command":"cd /h/p/shop && git log -1","description":"` + strings.Repeat("x", 200) + `…`, above, false},
		{"Bash", `{"command":"for f in /h/p/shop/*.orig; do rm $f; done"}`, above, true},
		{"Bash", `{"command":"find /h/p/shop -name '*.orig' | while read f; do rm \"$f\"; done"}`, above, true},
		{"Bash", `{"command":"git -C /h/p/main worktree remove --force /h/p/shop"}`, above, true},
		{"Bash", `{"command":"cat <<-EOF > /h/.cache/x\n\tdata\n\tEOF\nmake -C shop"}`, above, true},
		{"edit_file", `{"path":"shop/a.go","old":"a","new":"b"}`, above, true},
		{"Bash", `{"command":"ls /h/p | wc -l; find /h/p -name go.mod | xargs grep -l x; du -sh /h/p/*"}`, above, false},
		{"Bash", `{"command":"git -C shop format-patch -1 -o /h/.cache/x && git -C shop diff --output=/h/.cache/d.patch"}`, above, false},
		{"Bash", `{"command":"rsync -a /h/p/ /h/.cache/backup/"}`, above, false},
		{"Bash", `{"command":"sleep 1 & cd shop && make"}`, above, true},
		{"Bash", `{"command":"./server & cd shop && go test ./..."}`, above, true},
		{"Bash", `{"command":"for d in shop; do cd $d && git pull; done"}`, above, true},
		{"Bash", `{"command":"for d in ~/p/*/; do git -C \"$d\" pull; done"}`, above, true},
		{"Bash", `{"command":"for d in */; do git -C $d pull; done"}`, above, true},
		{"Bash", `{"command":"sed -i s/a/b/ ~/p/*/go.mod"}`, above, true},
		{"Bash", `{"command":"rm -rf */node_modules"}`, above, true},
		{"Bash", `{"command":"find ~/p -name '*.orig' -delete"}`, above, true},
		{"Bash", `{"command":"find ~/p -name go.mod | xargs sed -i s/a/b/"}`, above, true},
		{"Bash", `{"command":"awk '{print > \"/h/p/shop/x\"}' /h/.cache/f"}`, above, true},
		{"Bash", `{"command":"git -C /h/.cache/other diff --output=/h/p/shop/d.patch"}`, above, true},
		{"Bash", `{"command":"git -C shop format-patch -1"}`, above, true},
		// fail safe: a call it cannot read, or one the store cut in the tree
		{"mcp__x__y", `{"target":"/h/p/shop/a.go"}`, above, true},
		{"Write", `{"content":"long text that the store cut before its pa…`, above, false},
		{"Write", `{"content":"see /h/p/shop/a.go and the store cut before its pa…`, above, true},
		{"Bash", `{"command":"cd /h/p/shop && git log -1 && git sta…`, above, true},
	} {
		if got := ActsIn(c.tool, c.input, c.cwd, tree, home); got != c.acts {
			t.Errorf("%s %s in %s: acts %v, want %v", c.tool, c.input, c.cwd, got, c.acts)
		}
	}
}
